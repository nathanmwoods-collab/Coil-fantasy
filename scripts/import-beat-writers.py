"""Regenerate src/news/beatWriters.ts from the researched beat writer list.

Usage: python3 scripts/import-beat-writers.py /mnt/project-files/coil-fantasy/beat-writers.json

Rows match on team + name, so re-running after a monthly re-check just updates
the list. Every writer starts as "review": an admin approves or blocks them.
"""
import json
import re
import sys

src = json.load(open(sys.argv[1]))
rows = []
seen = set()
for w in src['writers']:
    key = (w['team'], w['name'].strip().lower())
    if key in seen:
        continue
    seen.add(key)
    national = w['team'] == 'NATIONAL'
    slug = re.sub(r'[^a-z0-9]+', '-', w['name'].lower()).strip('-')
    handle = (w.get('handle') or '').lstrip('@') or None
    rows.append({
        'id': f"beat:{w['team'].lower()}:{slug}",
        'name': w['name'],
        'tier': 'insider' if national else 'beat',
        'trust': 'review',
        'url': f'https://x.com/{handle}' if handle else w.get('url') or '',
        'kind': 'x' if handle else 'web',
        'category': 'national' if national else w['team'],
        'role': f"{'NFL insider' if national else 'Beat writer'}, {w['outlet']}" + (' · unverified' if w.get('confidence') == 'low' else ''),
        'verifiedFrom': w.get('verifiedFrom') or '',
    })

out = [
    '// Generated by scripts/import-beat-writers.py from researched bylines. Do not edit by hand.',
    f"// Source list generated {src.get('generatedAt', '')}. Every writer starts in review.",
    "import type { NewsSource } from './pipeline';",
    '',
    'export const BEAT_WRITERS: (NewsSource & { verifiedFrom: string })[] = ' + json.dumps(rows, indent=2, ensure_ascii=False) + ';',
    '',
]
open('src/news/beatWriters.ts', 'w').write('\n'.join(out))
print(len(rows), 'writers')
